import { chromium } from 'playwright';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--enable-webgl'] });
const page = await browser.newPage({ viewport: { width: 960, height: 540 } });
page.setDefaultTimeout(600000);
const logs = [];
page.on('console', (m) => logs.push(`[${m.type()}] ${m.text()}`));
page.on('pageerror', (e) => logs.push(e.message));
await page.goto(`http://localhost:5402/?manual=1&quality=high&play=1&view=race&race=roost-loop&spot=ghost&t=20&tod=0.55`, { waitUntil: 'load' });
await page.waitForFunction(() => window.__dw?.ready === true, null, { timeout: 600000 });
const r = await page.evaluate(() => {
  const g = window.__dw.game;
  window.__dw.advance(0.2);
  const rg = g.races.ghost;
  const canvas = g.renderer.canvas;
  const grab = () => { window.__dw.render(); const c2 = document.createElement('canvas'); c2.width = canvas.width; c2.height = canvas.height; const ctx = c2.getContext('2d'); ctx.drawImage(canvas, 0, 0); return ctx.getImageData(0, 0, c2.width, c2.height).data; };
  const diff = (a, b) => { let n = 0; for (let i = 0; i < a.length; i += 4) if (Math.abs(a[i] - b[i]) + Math.abs(a[i + 1] - b[i + 1]) + Math.abs(a[i + 2] - b[i + 2]) > 6) n++; return n; };
  const out = {};
  out.state = g.races.state; out.shown = rg.shown; out.groupVis = rg.group.visible;
  out.wyvernPos = rg.wyvern?.group.position.toArray().map(Math.round);
  out.cam = g.camera.position.toArray().map(Math.round);
  out.meshMat = rg.wyvern?.skinnedMesh?.material.map((m) => m.name);
  out.depthParent = !!rg.depthMesh?.parent;
  const all = grab();
  rg.group.visible = false; const none = grab(); rg.group.visible = true;
  out.all = diff(all, none);
  rg.streamers.mesh.visible = false; const noStream = grab(); out.bodyOnly = diff(noStream, none);
  rg.depthMesh.visible = false; const noDepth = grab(); out.noDepth = diff(noDepth, none);
  rg.depthMesh.visible = true; rg.streamers.mesh.visible = true;
  const withAll = grab(); out.withAll2 = diff(withAll, none);
  // Project the ghost center.
  const p = rg.wyvern.group.position.clone().project(g.camera);
  out.screen = [Math.round((p.x * 0.5 + 0.5) * 960), Math.round((0.5 - p.y * 0.5) * 540), p.z];
  out.info = g.renderer.gl.info.programs?.length;
  return out;
});
console.log(JSON.stringify(r, null, 1));
await page.evaluate(() => { document.getElementById('ui').style.display = 'none'; window.__dw.render(); });
await page.screenshot({ path: 'shots/ghostdbg.png' });
console.log(logs.filter((l) => /error|warn/i.test(l)).slice(0, 10).join('\n'));
await browser.close();
